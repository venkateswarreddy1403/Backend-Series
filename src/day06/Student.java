package day06;

public class Student {
    String name;
    int age;
    int Marks;

    Student() {

    }

    Student(String name) {
        this.name = name;
    }

    Student(String name, int age, int Marks) {
        this.name = name;
        this.age = age;
        this.Marks = Marks;
    }
}
